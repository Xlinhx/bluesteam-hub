import { execSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const dbContainer = process.env.POSTGRES_CONTAINER || 'bluesteam_db';
const backendContainer = process.env.BACKEND_CONTAINER || 'bluesteam_backend';
const dbUser = process.env.POSTGRES_USER || 'bluesteam';
const sourceDb = process.env.POSTGRES_DB || 'bluesteam';
const tempDb = 'bluesteam_restore_smoke';

const tempBackupDir = fs.mkdtempSync(path.join(os.tmpdir(), 'bluesteam-backup-smoke-'));
const tempMediaRestoreDir = fs.mkdtempSync(path.join(os.tmpdir(), 'bluesteam-media-restore-'));

function sha256File(filePath) {
  const buf = fs.readFileSync(filePath);
  return crypto.createHash('sha256').update(buf).digest('hex');
}

function isContainerRunning(containerName) {
  try {
    const out = execSync(
      `docker inspect -f "{{.State.Running}}" ${containerName}`,
      { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] },
    ).trim();
    return out === 'true';
  } catch {
    return false;
  }
}

console.log(`[restore-smoke] 1. Running full backup (DB + media files) into ${tempBackupDir}...`);
execSync(`node scripts/backup.mjs`, {
  env: {
    ...process.env,
    BACKUP_OUT_DIR: tempBackupDir,
  },
  stdio: 'inherit',
});

const manifests = fs
  .readdirSync(tempBackupDir)
  .filter((f) => f.endsWith('.manifest.json'))
  .sort();
if (manifests.length === 0) {
  throw new Error('No backup manifest generated by backup.mjs');
}
const manifestPath = path.join(tempBackupDir, manifests[manifests.length - 1]);

console.log(`[restore-smoke] 2. Recreating temporary database "${tempDb}"...`);
execSync(
  `docker exec ${dbContainer} psql -U ${dbUser} -d postgres -c "DROP DATABASE IF EXISTS ${tempDb};"`,
  { stdio: 'pipe' },
);
execSync(
  `docker exec ${dbContainer} psql -U ${dbUser} -d postgres -c "CREATE DATABASE ${tempDb};"`,
  { stdio: 'pipe' },
);

try {
  console.log(
    `[restore-smoke] 3. Restoring DB into "${tempDb}" and media into "${tempMediaRestoreDir}"...`,
  );
  execSync(`node scripts/restore.mjs "${manifestPath}"`, {
    env: {
      ...process.env,
      RESTORE_TARGET_DB: tempDb,
      RESTORE_TARGET_MEDIA_DIR: tempMediaRestoreDir,
    },
    stdio: 'inherit',
  });

  console.log(`[restore-smoke] 4. Comparing row counts between "${sourceDb}" and "${tempDb}"...`);
  const tables = [
    'topics',
    'resources',
    'models_3d',
    'activities',
    'creative_templates',
    'creative_materials',
    'rooms',
    'room_participants',
    'artworks',
    'media_assets',
  ];

  for (const table of tables) {
    const srcCount = execSync(
      `docker exec ${dbContainer} psql -U ${dbUser} -d ${sourceDb} -tAc "SELECT count(*) FROM ${table};"`,
      { encoding: 'utf8' },
    ).trim();
    const dstCount = execSync(
      `docker exec ${dbContainer} psql -U ${dbUser} -d ${tempDb} -tAc "SELECT count(*) FROM ${table};"`,
      { encoding: 'utf8' },
    ).trim();
    if (srcCount !== dstCount) {
      throw new Error(
        `Table ${table} count mismatch: source=${srcCount}, restored=${dstCount}`,
      );
    }
    console.log(`  - ${table}: ${dstCount} rows verified`);
  }

  console.log('[restore-smoke] 5. Verifying restored physical media files against DB metadata...');
  const mediaRowsRaw = execSync(
    `docker exec ${dbContainer} psql -U ${dbUser} -d ${tempDb} -tAF "|" -c "SELECT id, storage_key, byte_size, sha256 FROM media_assets WHERE status = 'ready';"`,
    { encoding: 'utf8' },
  )
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);

  let verifiedFiles = 0;
  const backendRunning = isContainerRunning(backendContainer);

  for (const line of mediaRowsRaw) {
    const [id, storageKey, byteSizeStr, expectedSha256] = line.split('|');
    if (!storageKey) continue;
    const restoredFilePath = path.join(tempMediaRestoreDir, storageKey);
    if (fs.existsSync(restoredFilePath)) {
      const actualSize = fs.statSync(restoredFilePath).size;
      const actualSha = sha256File(restoredFilePath);
      if (Number(byteSizeStr) !== actualSize) {
        throw new Error(
          `Restored media size mismatch for ${id} (${storageKey}): expected ${byteSizeStr}, got ${actualSize}`,
        );
      }
      if (expectedSha256 && expectedSha256 !== actualSha) {
        throw new Error(
          `Restored media SHA-256 mismatch for ${id} (${storageKey}): expected ${expectedSha256}, got ${actualSha}`,
        );
      }
      verifiedFiles += 1;
    } else if (backendRunning) {
      // Check if file exists inside the active backend container volume
      const existsInContainer = execSync(
        `docker exec ${backendContainer} sh -c "test -f '/data/uploads/${storageKey}' && echo yes || echo no"`,
        { encoding: 'utf8' },
      ).trim();
      if (existsInContainer === 'yes') {
        throw new Error(
          `Media file ${storageKey} exists in container volume but was missing from restored archive!`,
        );
      }
    }
  }

  console.log(
    `[restore-smoke] PASS: Backup and restore integrity verified across all core tables and ${verifiedFiles} physical media files.`,
  );
} finally {
  execSync(
    `docker exec ${dbContainer} psql -U ${dbUser} -d postgres -c "DROP DATABASE IF EXISTS ${tempDb};"`,
    { stdio: 'pipe' },
  );
  fs.rmSync(tempBackupDir, { recursive: true, force: true });
  fs.rmSync(tempMediaRestoreDir, { recursive: true, force: true });
}
