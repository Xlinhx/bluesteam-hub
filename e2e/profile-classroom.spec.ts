import path from 'node:path';
import { test,expect } from '@playwright/test';

test('teacher class setup, approval and the learner profile share real persisted evidence',async({page,browser})=>{
  test.setTimeout(90000);
  const stamp=crypto.randomUUID();
  const teacher=await page.request.post('/api/v1/auth/register',{data:{role:'teacher',email:`profile-teacher-${stamp}@example.test`,password:'Ocean-test-123',displayName:'Cô kiểm tra hồ sơ'}});
  expect(teacher.status()).toBe(201);
  const pupilContext=await browser.newContext({baseURL:process.env.PROFILE_E2E_BASE_URL || 'http://localhost:3010',viewport:{width:1536,height:1100},reducedMotion:'reduce'});
  const pupil=await pupilContext.newPage();
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));pupil.on('pageerror',error=>errors.push(error.message));
  try {
    const registered=await pupil.request.post('/api/v1/auth/register',{data:{role:'student',email:`profile-child-${stamp}@example.test`,password:'Ocean-test-123',displayName:'Bé kiểm tra hồ sơ'}});
    expect(registered.status()).toBe(201);
    await page.goto('/teacher/profile');
    await page.getByLabel('Ngày sinh',{exact:true}).fill('1994-08-12');
    await Promise.all([page.waitForResponse(response=>response.url().endsWith('/teacher/classroom/profile')&&response.request().method()==='PATCH'&&response.ok()),page.getByRole('button',{name:'Lưu thông tin',exact:true}).click()]);
    await page.reload();
    await expect(page.getByLabel('Ngày sinh',{exact:true})).toHaveValue('1994-08-12');
    await page.getByRole('button',{name:'Thiết lập lớp',exact:true}).click();
    await page.getByRole('textbox',{name:'Tạo trường mới',exact:true}).fill('Trường kiểm tra giao diện');
    await page.getByRole('button',{name:'Tạo trường',exact:true}).click();
    await page.getByRole('combobox',{name:'Trường',exact:true}).waitFor();
    const create=page.locator('form.teacher-class-create').last();
    await create.getByRole('textbox',{name:'Năm học',exact:true}).fill('2026–2027');
    await create.getByRole('textbox',{name:'Tên lớp',exact:true}).fill('Lá 1');
    await create.getByRole('textbox',{name:'Độ tuổi',exact:true}).fill('5–6 tuổi');
    await create.getByRole('button',{name:'Tạo lớp',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Thiết lập lớp Lá 1',exact:true})).toBeVisible();
    const age=page.getByRole('combobox',{name:'Độ tuổi',exact:true});
    await age.click();
    await page.getByRole('listbox',{name:'Độ tuổi',exact:true}).getByRole('option',{name:'Lớp ghép',exact:true}).click();
    await page.getByLabel('Ngày bắt đầu',{exact:true}).fill('2026-09-05');
    await page.getByLabel('Ngày kết thúc',{exact:true}).fill('2027-05-31');
    await page.getByRole('button',{name:'Lưu thiết lập',exact:true}).click();
    await expect(page.getByLabel('Ngày bắt đầu',{exact:true})).toHaveValue('2026-09-05');
    await expect(age).toContainText('Lớp ghép');
    const code=await page.locator('.teacher-invite-code').innerText();
    await pupil.goto('/profile');
    await pupil.getByRole('button',{name:'Tham gia bằng mã',exact:true}).click();
    await pupil.getByRole('textbox',{name:'Mã tham gia lớp',exact:true}).fill(code);
    await pupil.getByRole('button',{name:'Gửi yêu cầu vào lớp',exact:true}).click();
    await expect(pupil.getByText('Chờ cô xác nhận',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Danh sách học sinh',exact:true}).click();
    await page.reload();
    await page.getByRole('button',{name:'Danh sách học sinh',exact:true}).click();
    await page.getByRole('button',{name:'Duyệt',exact:true}).click();
    await pupil.reload();
    await expect(pupil.getByRole('combobox',{name:'Lớp',exact:true})).toContainText('Lá 1');
    await page.getByRole('button',{name:'Tổng quan lớp',exact:true}).click();
    const students=page.getByRole('combobox',{name:'Học sinh',exact:true});
    await students.click();
    const options=page.getByRole('listbox',{name:'Học sinh',exact:true});
    const pupilOption=options.getByRole('option',{name:'Bé kiểm tra hồ sơ',exact:true});
    await expect(pupilOption).toBeVisible();
    const avatar=await pupilOption.locator('.profile-option-avatar').boundingBox();
    expect(avatar?.width).toBeLessThanOrEqual(27);
    await pupilOption.click();
    await expect(students).toContainText('Bé kiểm tra hồ sơ');
    await students.press('ArrowDown');
    await expect(options).toBeVisible();
    await students.press('Escape');
    await expect(options).toBeHidden();
    expect((await pupil.request.post('/api/v1/learner-ocean/studied/upper-2')).status()).toBe(201);
    await pupil.reload();
    await expect(pupil.getByRole('region',{name:'Thành tích',exact:true}).locator('strong')).toHaveText('1');
    await expect(pupil.getByText(/huy hiệu/i)).toHaveCount(0);
    await page.reload();await page.getByRole('button',{name:'Danh sách học sinh',exact:true}).click();
    await page.getByRole('button',{name:'Bé kiểm tra hồ sơ →',exact:true}).click();
    await page.getByText('Xem tất cả huy hiệu',{exact:false}).click();
    const album=page.getByRole('dialog',{name:'Bộ sưu tập huy hiệu'});
    await expect(album.locator('.badge-tile')).toHaveCount(9);
    await expect(album.locator('.badge-tile[data-earned="true"]')).toHaveCount(1);
    await page.getByRole('combobox',{name:'Nhóm huy hiệu',exact:true}).click();
    await page.getByRole('listbox',{name:'Nhóm huy hiệu',exact:true}).getByRole('option',{name:'Khám phá',exact:true}).click();
    await expect(album.locator('.badge-tile')).toHaveCount(3);
    await album.getByRole('button',{name:'Đóng',exact:true}).click();
    if(process.env.PROFILE_SCREENSHOT_DIR) {
      const directory=process.env.PROFILE_SCREENSHOT_DIR;
      await page.getByRole('button',{name:'Tổng quan lớp',exact:true}).click();
      await page.setViewportSize({width:1536,height:1100});
      await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
      await page.screenshot({path:path.join(directory,'teacher-overview-web.png'),fullPage:true});
      await page.setViewportSize({width:1000,height:1568});
      await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
      await page.screenshot({path:path.join(directory,'teacher-overview-web-1000.png'),fullPage:true});
      await page.getByRole('button',{name:'Thiết lập lớp',exact:true}).click();
      await page.setViewportSize({width:1536,height:1100});
      await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
      await page.screenshot({path:path.join(directory,'teacher-settings-web.png'),fullPage:true});
      await page.setViewportSize({width:1000,height:1568});
      await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
      await page.screenshot({path:path.join(directory,'teacher-settings-web-1000.png'),fullPage:true});
      await pupil.setViewportSize({width:1000,height:1568});
      await pupil.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
      await pupil.screenshot({path:path.join(directory,'learner-profile-web-1000.png'),fullPage:true});
      await pupil.setViewportSize({width:1536,height:1100});
      await pupil.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
      await pupil.locator('.profile-hero').screenshot({path:path.join(directory,'hoc-sinh-thong-tin-ca-nhan.png')});
      await pupil.screenshot({path:path.join(directory,'learner-profile-web.png'),fullPage:true});
      for(const [label,target] of [['teacher',page],['learner',pupil]] as const) {
        await target.setViewportSize({width:390,height:844});
        await target.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
        await target.screenshot({path:path.join(directory,label+'-profile-web-390.png'),fullPage:true});
      }
      const pupilClass=pupil.getByRole('combobox',{name:'Lớp',exact:true});
      await pupilClass.click();
      await expect(pupil.getByRole('listbox',{name:'Lớp',exact:true})).toBeVisible();
      await pupil.screenshot({path:path.join(directory,'hoc-sinh-mobile-chon-lop.png')});
      await pupilClass.press('Escape');
    }
    for(const target of [page,pupil]) {
      await target.setViewportSize({width:390,height:844});
      expect(await target.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
      await expect(target.getByRole('progressbar')).toHaveCount(0);
    }
    expect(errors).toEqual([]);
  } finally {await pupilContext.close();}
});
